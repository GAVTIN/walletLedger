/**
 * Milestone 2, step 1: the two-session isolation lab.
 *
 * Runs two REAL Postgres sessions (A and B) against a scratch database that has the
 * real wallet schema, performs each experiment step by step, and writes the transcript
 * to docs/isolation.md. Nothing is simulated: every result below is what Postgres printed.
 *
 *   npm run lab:isolation
 *
 * To learn from it, do it by hand too: open two `psql` terminals and paste the lines
 * marked `A>` into one and `B>` into the other, in the order shown.
 */
import { writeFile } from 'node:fs/promises';
import pg from 'pg';
import { createPool } from '../src/db';
import { migrate } from '../src/db/migrate';

const ADMIN = process.env.LAB_ADMIN_URL ?? 'postgres://postgres@localhost:5432/postgres';
const LAB_DB = 'wallet_lab';
const url = ADMIN.replace(/\/[^/]*$/, `/${LAB_DB}`);

let out = '';
const w = (s = '') => {
  out += `${s}\n`;
};

type Sess = { name: 'A' | 'B'; c: pg.Client };
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function table(res: pg.QueryResult): string {
  if (!res.fields.length) return '';
  const cols = res.fields.map((f) => f.name);
  const rows = res.rows.map((r) => cols.map((c) => String(r[c])));
  const width = cols.map((c, i) => Math.max(c.length, ...rows.map((r) => r[i].length)));
  const line = (cells: string[]) => ` ${cells.map((c, i) => c.padEnd(width[i])).join(' | ')}`;
  return [line(cols), `-${width.map((n) => '-'.repeat(n + 2)).join('+')}`.replace(/^-/, ''), ...rows.map(line), `(${rows.length} row${rows.length === 1 ? '' : 's'})`].join('\n');
}

const fmtErr = (e: unknown) => {
  const err = e as { message: string; code?: string };
  return `ERROR:  ${err.message}\n(SQLSTATE ${err.code})`;
};

/** Run one statement, print it psql-style, print what came back. */
async function run(s: Sess, sql: string, params: unknown[] = []): Promise<pg.QueryResult | null> {
  w(`${s.name}> ${sql.replace(/\s+/g, ' ').trim()};`);
  try {
    const r = await s.c.query(sql, params);
    const t = ['BEGIN', 'COMMIT', 'ROLLBACK'].includes(sql.trim().split(/\s+/)[0].toUpperCase()) ? r.command : table(r) || `${r.command} ${r.rowCount}`;
    w(t);
    w();
    return r;
  } catch (e) {
    w(fmtErr(e));
    w();
    return null;
  }
}

/** Start a statement that is expected to BLOCK; returns a function that waits for its result. */
async function runBlocking(s: Sess, sql: string): Promise<() => Promise<pg.QueryResult | null>> {
  w(`${s.name}> ${sql.replace(/\s+/g, ' ').trim()};`);
  let settled = false;
  const p = s.c.query(sql).then(
    (r) => ((settled = true), { r, e: null as unknown }),
    (e) => ((settled = true), { r: null, e }),
  );
  await sleep(400);
  w(settled ? '-- (returned immediately)' : `-- ...${s.name} is BLOCKED: it is waiting for the other session`);
  w();
  return async () => {
    const { r, e } = await p;
    w(`-- ${s.name}'s waiting statement finishes:`);
    if (e) w(fmtErr(e));
    else w(table(r!) || `${r!.command} ${r!.rowCount}`);
    w();
    return r;
  };
}

async function main() {
  const admin = new pg.Client({ connectionString: ADMIN });
  await admin.connect();
  await admin.query(`DROP DATABASE IF EXISTS ${LAB_DB} WITH (FORCE)`);
  await admin.query(`CREATE DATABASE ${LAB_DB}`);
  await admin.end();
  const setup = createPool(url, 2);
  await migrate(setup);
  const u = (await setup.query(`INSERT INTO users (name, email, phone) VALUES ('Lab User', 'lab@example.com', '+910000000001') RETURNING id`)).rows[0].id;
  const X = (await setup.query(`INSERT INTO accounts (kind, user_id, name, balance) VALUES ('USER_WALLET', $1, 'main', 100000) RETURNING id`, [u])).rows[0].id;
  const Y = (await setup.query(`INSERT INTO accounts (kind, user_id, name, balance) VALUES ('USER_WALLET', $1, 'savings', 100000) RETURNING id`, [u])).rows[0].id;
  await setup.end();

  const mk = async (name: 'A' | 'B'): Promise<Sess> => {
    const c = new pg.Client({ connectionString: url });
    await c.connect();
    return { name, c };
  };
  const A = await mk('A');
  const B = await mk('B');
  const reset = async () => {
    for (const s of [A, B]) await s.c.query('ROLLBACK').catch(() => {});
    await A.c.query(`UPDATE accounts SET balance = 100000 WHERE id IN (${X}, ${Y})`);
    await A.c.query(`UPDATE users SET name = 'Lab User' WHERE id = ${u}`);
    await A.c.query(`DELETE FROM accounts WHERE name = 'phantom'`);
  };
  const bal = `SELECT id, balance FROM accounts WHERE id = ${X}`;
  const spend = `UPDATE accounts SET balance = balance - 30000 WHERE id = ${X}`;

  w('# Isolation lab: two sessions, real output');
  w();
  w(`Generated by \`npm run lab:isolation\` against PostgreSQL ${(await A.c.query('SHOW server_version')).rows[0].server_version}.`);
  w(`Everything below is real output from two live sessions (**A** and **B**). Wallet \`${X}\` ("main") starts with **100000 paise (Rs 1,000)**.`);
  w('Each `A>` / `B>` line is exactly what you would type into that session\'s `psql`; do the same in two terminals to see it yourself.');
  w();

  // ------------------------------------------------------------------ case 1
  w('## Case 1: READ COMMITTED (the Postgres default)');
  w();
  w('Question: A reads a balance, B changes it and commits, A reads again. Does A see a different value?');
  w();
  w('```');
  await reset();
  await run(A, 'BEGIN');
  await run(A, bal);
  await run(B, 'BEGIN');
  await run(B, spend);
  await run(B, 'COMMIT');
  await run(A, bal);
  await run(A, 'COMMIT');
  w('```');
  w();
  w('**Answer: yes.** Inside ONE transaction A read 100000, then 70000. Each *statement* gets a fresh snapshot of whatever is committed at that moment (a "non-repeatable read"). For money this means: anything you read and then act on is stale unless you lock it.');
  w();

  // ------------------------------------------------------------------ case 2
  w('## Case 2: REPEATABLE READ');
  w();
  w('Same steps, but A opens its transaction with `ISOLATION LEVEL REPEATABLE READ`.');
  w();
  w('```');
  await reset();
  await run(A, 'BEGIN ISOLATION LEVEL REPEATABLE READ');
  await run(A, bal);
  await run(B, 'BEGIN');
  await run(B, spend);
  await run(B, 'COMMIT');
  await run(A, bal);
  w('-- A now tries to act on what it saw (spend Rs 100 from its stale view):');
  await run(A, `UPDATE accounts SET balance = balance - 10000 WHERE id = ${X}`);
  await run(A, 'ROLLBACK');
  w('```');
  w();
  w('**Answer: no, A keeps seeing 100000** (one snapshot for the whole transaction). But the lesson is the last step: when A tries to *write* a row that B changed after A\'s snapshot, Postgres refuses with `could not serialize access due to concurrent update` (SQLSTATE 40001). The database protects you from a lost update, at the price of an error your code must catch and retry.');
  w();

  // ------------------------------------------------------------------ case 3
  w('## Case 3: SERIALIZABLE, two sessions read a balance then write based on it');
  w();
  w('```');
  await reset();
  await run(A, 'BEGIN ISOLATION LEVEL SERIALIZABLE');
  await run(B, 'BEGIN ISOLATION LEVEL SERIALIZABLE');
  await run(A, bal);
  await run(B, bal);
  w('-- both decided "100000 - 30000 = 70000" from the value they read, and write that number:');
  await run(A, `UPDATE accounts SET balance = 70000 WHERE id = ${X}`);
  const waitB = await runBlocking(B, `UPDATE accounts SET balance = 70000 WHERE id = ${X}`);
  await run(A, 'COMMIT');
  await waitB();
  await run(B, 'ROLLBACK');
  w('```');
  w();
  w('**Answer: B fails** with `could not serialize access due to concurrent update` (40001). Without it, both transactions would have believed they spent Rs 300, yet the balance would have fallen by Rs 300 only once: a classic lost update, where one spend silently disappears. B must roll back and retry from the start (it will then read the new balance).');
  w();
  w('### Case 3b: write skew (the anomaly REPEATABLE READ does NOT stop)');
  w();
  w(`Rule both sessions enforce in code: "a user's wallets must always hold at least Rs 1,000 in total". The user has wallet ${X} (100000) and wallet ${Y} (100000). Each session checks the total, then drains a *different* wallet.`);
  w();
  const skew = async (level: string) => {
    await reset();
    await run(A, `BEGIN ISOLATION LEVEL ${level}`);
    await run(B, `BEGIN ISOLATION LEVEL ${level}`);
    await run(A, `SELECT sum(balance) AS total FROM accounts WHERE user_id = ${u}`);
    await run(B, `SELECT sum(balance) AS total FROM accounts WHERE user_id = ${u}`);
    w('-- 200000 >= 100000, so each thinks it is safe to drain ONE wallet:');
    await run(A, `UPDATE accounts SET balance = 0 WHERE id = ${X}`);
    await run(B, `UPDATE accounts SET balance = 0 WHERE id = ${Y}`);
    await run(A, 'COMMIT');
    await run(B, 'COMMIT');
    await run(A, `SELECT sum(balance) AS total_after FROM accounts WHERE user_id = ${u}`);
  };
  w('**REPEATABLE READ:**');
  w();
  w('```');
  await skew('REPEATABLE READ');
  w('```');
  w();
  w('**SERIALIZABLE:**');
  w();
  w('```');
  await skew('SERIALIZABLE');
  w('```');
  w();
  w('**Answer:** under REPEATABLE READ both commit and the total ends at 0, breaking the rule (no row was written by both, so there is no "concurrent update" to detect). Under SERIALIZABLE Postgres notices the read/write dependency cycle and aborts one session with `could not serialize access due to read/write dependencies among transactions` (40001).');
  w();

  // ------------------------------------------------------------------ case 4
  w('## Case 4: REPEATABLE READ with a JOIN');
  w();
  w('Does the guarantee still hold when the query joins two tables? A runs a join of `accounts` and `users`; B changes a balance, renames the user and adds a new wallet, then commits.');
  w();
  const join = `SELECT a.id, a.balance, u.name FROM accounts a JOIN users u ON u.id = a.user_id WHERE u.id = ${u} ORDER BY a.id`;
  const mutate = async () => {
    await run(B, 'BEGIN');
    await run(B, spend);
    await run(B, `UPDATE users SET name = 'Renamed User' WHERE id = ${u}`);
    await run(B, `INSERT INTO accounts (kind, user_id, name, balance) VALUES ('USER_WALLET', ${u}, 'phantom', 5)`);
    await run(B, 'COMMIT');
  };
  w('**REPEATABLE READ:**');
  w();
  w('```');
  await reset();
  await run(A, 'BEGIN ISOLATION LEVEL REPEATABLE READ');
  await run(A, join);
  await mutate();
  await run(A, join);
  await run(A, 'COMMIT');
  w('```');
  w();
  w('**Control, READ COMMITTED:**');
  w();
  w('```');
  await reset();
  await run(A, 'BEGIN ISOLATION LEVEL READ COMMITTED');
  await run(A, join);
  await mutate();
  await run(A, join);
  await run(A, 'COMMIT');
  w('```');
  w();
  w('**Answer: yes, the guarantee holds in PostgreSQL.** The snapshot belongs to the *transaction*, not to a table or a statement, so both sides of the join (and any rows that would have appeared, "phantoms") stay frozen. In the control run, READ COMMITTED shows the new balance, the new name and the extra wallet.');
  w();

  // ------------------------------------------------------------------ case 5 (the fix)
  w('## Case 5: the fix we actually use, `SELECT ... FOR UPDATE` at READ COMMITTED');
  w();
  w('B tries to take the row lock while A holds it; B must wait, and when it proceeds it reads the *fresh* balance.');
  w();
  w('```');
  await reset();
  await run(A, 'BEGIN');
  await run(A, `${bal} FOR UPDATE`);
  await run(B, 'BEGIN');
  const waitB5 = await runBlocking(B, `${bal} FOR UPDATE`);
  await run(A, spend);
  await run(A, 'COMMIT');
  await waitB5();
  await run(B, 'COMMIT');
  w('```');
  w();
  w('**Answer:** B was blocked until A committed, then read **70000**, not the stale 100000. Reading under the lock means the balance you check is the balance you update. That is why the transfer code locks first, re-reads, then decides.');
  w();

  // ------------------------------------------------------------------ case 6 (deadlock)
  w('## Case 6: why the lock ORDER matters (deadlock)');
  w();
  w(`A locks wallet ${X} then wants ${Y}. B locks ${Y} then wants ${X}. (\`deadlock_timeout\` lowered to 200ms so the lab is quick.)`);
  w();
  w('```');
  await reset();
  await A.c.query("SET deadlock_timeout = '200ms'");
  await B.c.query("SET deadlock_timeout = '200ms'");
  await run(A, 'BEGIN');
  await run(B, 'BEGIN');
  await run(A, `SELECT id FROM accounts WHERE id = ${X} FOR UPDATE`);
  await run(B, `SELECT id FROM accounts WHERE id = ${Y} FOR UPDATE`);
  const waitA6 = await runBlocking(A, `SELECT id FROM accounts WHERE id = ${Y} FOR UPDATE`);
  await run(B, `SELECT id FROM accounts WHERE id = ${X} FOR UPDATE`);
  await waitA6();
  await run(A, 'ROLLBACK');
  await run(B, 'ROLLBACK');
  w('```');
  w();
  w(`**Answer:** each waits for the other forever, so Postgres detects the cycle and kills one with \`deadlock detected\` (40P01). If BOTH sessions always lock the lower id first (here ${Math.min(X, Y)}), the second one simply waits its turn and no cycle can form. That is the rule in \`lockAccounts()\`.`);

  await A.c.end();
  await B.c.end();
  const admin2 = new pg.Client({ connectionString: ADMIN });
  await admin2.connect();
  await admin2.query(`DROP DATABASE IF EXISTS ${LAB_DB} WITH (FORCE)`);
  await admin2.end();

  await writeFile(new URL('../docs/isolation.md', import.meta.url), out);
  console.log(`wrote docs/isolation.md (${out.split('\n').length} lines)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
