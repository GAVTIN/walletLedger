/**
 * Milestone 5, part A: "measure how much time the rules add to a transfer".
 *
 *   npm run lab:bench     (clones the seeded `wallet` database, writes docs/rules-latency.md)
 *
 * 300 sequential Rs 10 transfers, each from a DIFFERENT seeded wallet (so no rule fires),
 * measured end to end through the API handler (idempotency + transaction + locks + rules),
 * once with every rule disabled and once with all four enabled.
 */
import { writeFile } from 'node:fs/promises';
import pg from 'pg';
import { config } from '../src/config';
import { createPool } from '../src/db';
import { makeApi } from '../test/helpers/api';

const ADMIN = process.env.LAB_ADMIN_URL ?? 'postgres://postgres@localhost:5432/postgres';
const SRC_DB = process.env.SEEDED_DB ?? 'wallet';
const CLONE = 'wallet_rules_bench';
const pct = (a: number[], p: number) => [...a].sort((x, y) => x - y)[Math.min(a.length - 1, Math.floor((p / 100) * a.length))];

async function main() {
  const admin = new pg.Client({ connectionString: ADMIN });
  await admin.connect();
  await admin.query(`DROP DATABASE IF EXISTS ${CLONE} WITH (FORCE)`);
  await admin.query(`CREATE DATABASE ${CLONE} TEMPLATE ${SRC_DB}`);
  await admin.end();
  const pool = createPool(ADMIN.replace(/\/[^/]*$/, `/${CLONE}`), 10);
  const api = await makeApi(pool, undefined, config);

  const senders = (
    await pool.query(
      `SELECT a.id AS wallet, a.user_id, (SELECT b.id FROM accounts b WHERE b.user_id <> a.user_id AND b.kind='USER_WALLET' ORDER BY b.id LIMIT 1) AS dest
         FROM accounts a WHERE a.kind = 'USER_WALLET' AND a.balance >= 1000000 ORDER BY a.id LIMIT 700`,
    )
  ).rows;
  if (senders.length < 700) throw new Error('need more funded wallets; run the seed first');

  const measure = async (rows: typeof senders) => {
    const ms: number[] = [];
    for (const r of rows) {
      const t0 = performance.now();
      const res = await api.post('/transfers', { from_wallet_id: r.wallet, to_wallet_id: r.dest, amount: 1_000 }, { user: r.user_id });
      ms.push(performance.now() - t0);
      if (res.status !== 201 || res.body.flags.length) throw new Error(`unexpected ${res.status} ${res.raw}`);
    }
    return ms;
  };
  await measure(senders.slice(0, 40)); // warm-up
  await pool.query('UPDATE risk_rules SET enabled = false');
  const off = await measure(senders.slice(40, 340));
  await pool.query('UPDATE risk_rules SET enabled = true');
  const on = await measure(senders.slice(340, 640));
  const mean = (a: number[]) => a.reduce((s, x) => s + x, 0) / a.length;

  const md = `# What do the fraud rules cost per transfer? (generated by \`npm run lab:bench\`)

300 sequential Rs 10 transfers per row, each from a different wallet of the 100,000-transfer seeded database (so no rule fires and every transfer completes), measured end to end inside the API handler.

| | mean | median | p95 |
|---|---|---|---|
| all rules **disabled** | ${mean(off).toFixed(2)} ms | ${pct(off, 50).toFixed(2)} ms | ${pct(off, 95).toFixed(2)} ms |
| all 4 rules **enabled** | ${mean(on).toFixed(2)} ms | ${pct(on, 50).toFixed(2)} ms | ${pct(on, 95).toFixed(2)} ms |
| **added by the rules** | **${(mean(on) - mean(off)).toFixed(2)} ms** (${(((mean(on) - mean(off)) / mean(off)) * 100).toFixed(0)}%) | ${(pct(on, 50) - pct(off, 50)).toFixed(2)} ms | ${(pct(on, 95) - pct(off, 95)).toFixed(2)} ms |

The rules add 1 query to load \`risk_rules\` plus 3 indexed lookups (VELOCITY, DAILY_VOLUME, NEW_RECIPIENT_HIGH; LARGE_AMOUNT needs none). Single-digit-millisecond cost is for a *local* database; over a real network each extra query also pays a round trip, which is why loading the rules in one query matters.
`;
  await writeFile(new URL('../docs/rules-latency.md', import.meta.url), md);
  console.log(md);
  await pool.end();
  const a2 = new pg.Client({ connectionString: ADMIN });
  await a2.connect();
  await a2.query(`DROP DATABASE IF EXISTS ${CLONE} WITH (FORCE)`);
  await a2.end();
}
main().catch((e) => {
  console.error(e);
  process.exit(1);
});
