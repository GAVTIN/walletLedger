/**
 * Performance lab: EXPLAIN ANALYZE against ~1 million ledger entries.
 *
 *   npm run seed -- (into a scratch DB) with --users 2000 --transfers 500000
 *   BENCH_DATABASE_URL=postgres://postgres@localhost:5432/wallet_bench npm run lab:explain
 *
 * Writes docs/explain.md. Each query is run twice and the SECOND (warm cache) run is reported.
 * Sections: (A) the 5 reconciliation checks, (B) statement pagination OFFSET vs keyset,
 * (C) the fraud-rule queries, (D) what an index costs on every write.
 */
import '../src/env';
import { writeFile } from 'node:fs/promises';
import type pg from 'pg';
import { createPool } from '../src/db';
import {
  SQL_GLOBAL, SQL_NO_ENTRIES, SQL_ORPHAN_ENTRIES, SQL_OVERDRAFT, SQL_STORED, SQL_TRANSFER, SQL_UNEXPECTED_ENTRIES,
} from '../src/recon/reconcile';

const BENCH_URL = process.env.BENCH_DATABASE_URL ??
  (process.env.TEST_ADMIN_URL ?? 'postgres://postgres@localhost:5432/postgres').replace(/\/[^/?]*(\?.*)?$/, '/wallet_bench$1');
const pool = createPool(BENCH_URL, 4);

let md = '';
const w = (s = '') => {
  md += `${s}\n`;
  console.log(s);
};

type Plan = { lines: string[]; ms: number };
async function explain(c: pg.PoolClient | pg.Pool, sql: string, params: unknown[] = []): Promise<Plan> {
  const run = async () => {
    const r = await c.query(`EXPLAIN (ANALYZE, BUFFERS, COSTS OFF) ${sql}`, params);
    const lines = r.rows.map((x) => x['QUERY PLAN'] as string);
    return { lines, ms: Number(/Execution Time: ([\d.]+) ms/.exec(lines.join('\n'))![1]) };
  };
  await run(); // warm the cache
  return run();
}
const excerpt = (p: Plan, n = 16) => `\`\`\`\n${p.lines.filter((l) => !/Planning Time|Buffers: shared hit=\d+$/.test(l)).slice(0, n).join('\n')}\n\`\`\``;
const scanKinds = (p: Plan) => [...new Set(p.lines.flatMap((l) => /(Seq Scan|Index Only Scan|Index Scan|Bitmap Heap Scan|Parallel Seq Scan)/.exec(l)?.[1] ?? []))].join(', ') || '-';

async function withoutIndex<T>(index: string, fn: (c: pg.PoolClient) => Promise<T>): Promise<T> {
  const c = await pool.connect();
  try {
    await c.query('BEGIN');
    await c.query(`DROP INDEX ${index}`);
    return await fn(c);
  } finally {
    await c.query('ROLLBACK'); // the index comes back: nothing is changed
    c.release();
  }
}

async function ensureWhale(): Promise<{ wallet: number; userId: number }> {
  const ex = await pool.query(`SELECT a.id AS wallet, a.user_id FROM accounts a JOIN users u ON u.id = a.user_id WHERE u.email = 'whale@bench.example'`);
  if (ex.rows[0]) return { wallet: ex.rows[0].wallet, userId: ex.rows[0].user_id };
  const c = await pool.connect();
  try {
    await c.query('BEGIN');
    const u = (await c.query(`INSERT INTO users (name, email, phone, kyc_status) VALUES ('Whale', 'whale@bench.example', '+910000099999', 'VERIFIED') RETURNING id`)).rows[0].id;
    const wallet = (await c.query(`INSERT INTO accounts (kind, user_id, name) VALUES ('USER_WALLET', $1, 'main') RETURNING id`, [u])).rows[0].id;
    const cashIn = (await c.query(`SELECT id FROM accounts WHERE system_code = 'CASH_IN'`)).rows[0].id;
    // 250,000 one-rupee top-ups spread over ~11 months: a wallet with a very long statement
    await c.query(
      `INSERT INTO transfers (id, type, status, amount, source_account_id, destination_account_id, initiated_by_user_id, created_at)
       OVERRIDING SYSTEM VALUE
       SELECT nextval(pg_get_serial_sequence('transfers', 'id')), 'TOPUP', 'COMPLETED', 100, $1, $2, $3,
              now() - (g * interval '2 minutes')
         FROM generate_series(1, 250000) g`,
      [cashIn, wallet, u],
    );
    await c.query(
      `INSERT INTO ledger_entries (transfer_id, account_id, direction, amount, created_at)
       SELECT id, source_account_id, 'D', amount, created_at FROM transfers WHERE destination_account_id = $1
       UNION ALL
       SELECT id, destination_account_id, 'C', amount, created_at FROM transfers WHERE destination_account_id = $1`,
      [wallet],
    );
    await c.query('UPDATE accounts SET balance = balance + 25000000 WHERE id = $1', [wallet]);
    await c.query('UPDATE accounts SET balance = balance - 25000000 WHERE id = $1', [cashIn]);
    await c.query('COMMIT');
    return { wallet, userId: u };
  } catch (e) {
    await c.query('ROLLBACK');
    throw e;
  } finally {
    c.release();
  }
}

async function main() {
  const counts = (await pool.query(`SELECT (SELECT count(*) FROM ledger_entries)::bigint AS e, (SELECT count(*) FROM transfers)::bigint AS t, (SELECT count(*) FROM accounts)::bigint AS a`)).rows[0];
  const whale = await ensureWhale();
  await pool.query('ANALYZE');
  const ec = (await pool.query('SELECT count(*)::bigint AS e FROM ledger_entries')).rows[0].e;
  const pgv = (await pool.query('SHOW server_version')).rows[0].server_version;

  w('# EXPLAIN ANALYZE results (generated by `npm run lab:explain`)');
  w();
  w(`PostgreSQL ${pgv}, default settings, in a small cloud sandbox. **${Number(ec).toLocaleString('en-US')} ledger entries** (1,000,000 from the seed plus 500,000 for one long-statement wallet), ${Number(counts.t).toLocaleString('en-US')}+ transfers, ${counts.a} accounts.`);
  w('Each query ran twice; the **second (warm cache)** execution time is shown. Absolute times depend on the machine; the *shapes* (scan type, rows touched, growth with OFFSET) are what matter.');
  w();

  // ------------------------------------------------------------------ A
  w('## A. Reconciliation checks (the exact SQL the nightly job runs)');
  w();
  const checks: [string, string][] = [
    ['1 GLOBAL_BALANCE (sum debits = sum credits)', SQL_GLOBAL],
    ['2 TRANSFER_BALANCE (GROUP BY transfer HAVING)', SQL_TRANSFER],
    ['3 STORED_BALANCE (stored vs computed)', SQL_STORED],
    ['4 NO_OVERDRAFT (computed < 0)', SQL_OVERDRAFT],
    ['5a ORPHAN: completed transfer without entries', SQL_NO_ENTRIES],
    ['5b ORPHAN: held/rejected transfer WITH entries', SQL_UNEXPECTED_ENTRIES],
    ['5c ORPHAN: entry without transfer', SQL_ORPHAN_ENTRIES],
  ];
  const plans: Plan[] = [];
  w('| Check | Time | Scan types in plan |');
  w('|---|---|---|');
  for (const [name, sql] of checks) {
    const p = await explain(pool, sql);
    plans.push(p);
    w(`| ${name} | **${p.ms.toFixed(0)} ms** | ${scanKinds(p)} |`);
  }
  const total = plans.reduce((s, p) => s + p.ms, 0);
  w();
  w(`All seven queries together: **${(total / 1000).toFixed(2)} s** on ${Number(ec).toLocaleString('en-US')} entries.`);
  w();
  w('### Do the checks actually USE an index? (each index dropped inside a transaction, then rolled back)');
  w();
  w('| Query | Index dropped | With index | Without it |');
  w('|---|---|---|---|');
  for (const [name, sql, idx] of [
    ['2 TRANSFER_BALANCE', SQL_TRANSFER, 'ledger_entries_transfer_idx'],
    ['3 STORED_BALANCE', SQL_STORED, 'ledger_entries_account_time_idx'],
    ['4 NO_OVERDRAFT', SQL_OVERDRAFT, 'ledger_entries_account_time_idx'],
    ['5a completed transfer without entries', SQL_NO_ENTRIES, 'ledger_entries_transfer_idx'],
    ['5b held/rejected with entries', SQL_UNEXPECTED_ENTRIES, 'ledger_entries_transfer_idx'],
  ] as const) {
    const withIdx = await explain(pool, sql);
    const without = await withoutIndex(idx, (c) => explain(c, sql));
    w(`| ${name} | \`${idx}\` | ${withIdx.ms.toFixed(0)} ms (${scanKinds(withIdx)}) | ${without.ms.toFixed(0)} ms (${scanKinds(without)}) |`);
  }
  w();
  w('Plans for the two most expensive checks:');
  w();
  const order = plans.map((p, i) => [p.ms, i] as const).sort((a, b) => b[0] - a[0]).slice(0, 2);
  for (const [, i] of order) {
    w(`**${checks[i][0]}**`);
    w();
    w(excerpt(plans[i], 18));
    w();
  }

  // ------------------------------------------------------------------ B
  w('## B. Statement pagination: OFFSET vs keyset (cursor)');
  w();
  w(`Wallet ${whale.wallet} has 250,000 statement entries. Same query shape as \`GET /wallets/:id/statement\`.`);
  w();
  const base = `SELECT e.id, e.transfer_id, e.direction, e.amount, e.created_at, t.type, t.status, t.note,
          CASE WHEN e.direction = 'D' THEN t.destination_account_id ELSE t.source_account_id END AS counterparty
     FROM ledger_entries e JOIN transfers t ON t.id = e.transfer_id
    WHERE e.account_id = $1`;
  const order_ = 'ORDER BY e.created_at DESC, e.id DESC';
  w('| Page requested | OFFSET query | Rows produced before LIMIT/OFFSET discarded them | Plan |');
  w('|---|---|---|---|');
  let offsetPlan: Plan | null = null;
  for (const off of [0, 1_000, 10_000, 100_000, 200_000]) {
    const p = await explain(pool, `${base} ${order_} LIMIT 20 OFFSET ${off}`, [whale.wallet]);
    // rows the plan had to produce BEFORE the LIMIT/OFFSET discarded them = the node directly under "Limit"
    const li = p.lines.findIndex((l) => l.trimStart().startsWith('Limit'));
    const child = p.lines.slice(li + 1).find((l) => l.includes('->')) ?? '';
    const rows = Number(/rows=(\d+)/.exec(child)?.[1] ?? 0);
    const top = /->\s+([A-Za-z ]+?)(?: using| on|\s*\()/.exec(child)?.[1]?.trim() ?? '?';
    w(`| OFFSET ${off.toLocaleString('en-US')} | **${p.ms.toFixed(1)} ms** | ${rows.toLocaleString('en-US')} | ${top} |`);
    if (off === 100_000) offsetPlan = p;
  }
  // keyset at the SAME position: fetch the boundary row, then ask for "the 20 after it"
  const boundary = (await pool.query(`SELECT created_at, id FROM ledger_entries WHERE account_id = $1 ORDER BY created_at DESC, id DESC OFFSET 99999 LIMIT 1`, [whale.wallet])).rows[0];
  const ks = await explain(pool, `${base} AND (e.created_at, e.id) < ($2::timestamptz, $3::bigint) ${order_} LIMIT 20`, [whale.wallet, boundary.created_at, boundary.id]);
  const ks0 = await explain(pool, `${base} ${order_} LIMIT 20`, [whale.wallet]);
  w();
  w(`Keyset (cursor) for the **same rows as OFFSET 100,000**: **${ks.ms.toFixed(2)} ms** (page 1 by keyset: ${ks0.ms.toFixed(2)} ms): the cost does not grow with depth.`);
  w();
  w('**OFFSET 100000 plan:**');
  w();
  w(excerpt(offsetPlan!, 14));
  w();
  w('**Keyset plan (same page):**');
  w();
  w(excerpt(ks, 12));
  w();

  // ------------------------------------------------------------------ C
  w('## C. Fraud-rule queries and the indexes that serve them');
  w();
  const busy = (await pool.query(`SELECT source_account_id AS w, destination_account_id AS d FROM transfers WHERE type = 'PEER_TRANSFER' AND source_account_id IN (SELECT source_account_id FROM transfers WHERE type='PEER_TRANSFER' GROUP BY 1 ORDER BY count(*) DESC LIMIT 1) LIMIT 1`)).rows[0];
  const velocity = `SELECT count(*)::int AS n FROM transfers WHERE source_account_id = $1 AND type IN ('PEER_TRANSFER','WITHDRAWAL') AND status IN ('COMPLETED','HELD','REVERSED') AND created_at >= now() - make_interval(mins => 10)`;
  const daily = `SELECT COALESCE(SUM(amount),0) FROM transfers WHERE source_account_id = $1 AND type IN ('PEER_TRANSFER','WITHDRAWAL') AND status IN ('COMPLETED','HELD','REVERSED') AND created_at >= now() - make_interval(hours => 24)`;
  const recipient = `SELECT EXISTS (SELECT 1 FROM transfers WHERE source_account_id = $1 AND destination_account_id = $2 AND status IN ('COMPLETED','REVERSED'))`;
  w('Measured on the busiest sender in the data set (a wallet with the most outgoing transfers).');
  w();
  w('| Rule query | Index it uses | With index | Index dropped |');
  w('|---|---|---|---|');
  for (const [name, sql, idx, params] of [
    ['VELOCITY (10 min window)', velocity, 'transfers_source_created_idx', [busy.w]],
    ['DAILY_VOLUME (24 h window)', daily, 'transfers_source_created_idx', [busy.w]],
    ['NEW_RECIPIENT_HIGH', recipient, 'transfers_source_dest_idx', [busy.w, busy.d]],
  ] as const) {
    const a = await explain(pool, sql, [...params]);
    const b = await withoutIndex(idx, (c) => explain(c, sql, [...params]));
    w(`| ${name} | \`${idx}\` | ${a.ms.toFixed(2)} ms (${scanKinds(a)}) | ${b.ms.toFixed(1)} ms (${scanKinds(b)}) |`);
  }
  w();
  w('(LARGE_AMOUNT compares the request\'s own amount against a threshold: no query, no index.)');
  w();

  w('### C2. Why the dedicated index exists: a sender with a LONG history');
  w();
  w('The busiest *ordinary* wallet has only a few hundred outgoing transfers, so even the second-best index (leading column `source_account_id`) is fast. The index that matters is the one that stays fast for a wallet with a very long history. Measured on a scratch copy of `transfers` where one sender has **300,000** outgoing transfers:');
  w();
  {
    const c2 = await pool.connect();
    try {
      await c2.query('CREATE TEMP TABLE transfers_x AS SELECT id, type, status, amount, source_account_id, destination_account_id, created_at FROM transfers');
      await c2.query(`INSERT INTO transfers_x (id, type, status, amount, source_account_id, destination_account_id, created_at)
                      SELECT -g, 'PEER_TRANSFER', 'COMPLETED', 100, $1, (g % 50) + 1000, now() - (g * interval '90 seconds') FROM generate_series(1, 300000) g`, [busy.w]);
      await c2.query('CREATE INDEX ON transfers_x (source_account_id, destination_account_id)');
      await c2.query('ANALYZE transfers_x');
      const q = (t: string) => `SELECT count(*)::int AS n FROM ${t} WHERE source_account_id = $1 AND type IN ('PEER_TRANSFER','WITHDRAWAL') AND status IN ('COMPLETED','HELD','REVERSED') AND created_at >= now() - make_interval(mins => 10)`;
      const without = await explain(c2, q('transfers_x'), [busy.w]);
      await c2.query('CREATE INDEX transfers_x_src_created ON transfers_x (source_account_id, created_at DESC)');
      await c2.query('ANALYZE transfers_x');
      const withIdx = await explain(c2, q('transfers_x'), [busy.w]);
      w('| VELOCITY query for the heavy sender | Time | Plan |');
      w('|---|---|---|');
      w(`| only the (source, destination) index available | **${without.ms.toFixed(1)} ms** | ${scanKinds(without)} |`);
      w(`| with \`(source_account_id, created_at DESC)\` | **${withIdx.ms.toFixed(2)} ms** | ${scanKinds(withIdx)} |`);
    } finally {
      await c2.query('DROP TABLE IF EXISTS transfers_x').catch(() => {});
      c2.release();
    }
  }
  w();

  // ------------------------------------------------------------------ D
  w('## D. Every index slows writes (300,000-row insert, same data, different index sets)');
  w();
  const c = await pool.connect();
  try {
    const results: [string, number][] = [];
    for (const [label, ddl] of [
      ['primary key only', []],
      ['+ (account_id, created_at DESC, id DESC)', ['CREATE INDEX ON bench_e (account_id, created_at DESC, id DESC)']],
      ['+ (transfer_id)', ['CREATE INDEX ON bench_e (transfer_id)']],
      ['+ both (what ledger_entries has)', ['CREATE INDEX ON bench_e (account_id, created_at DESC, id DESC)', 'CREATE INDEX ON bench_e (transfer_id)']],
    ] as [string, string[]][]) {
      await c.query('DROP TABLE IF EXISTS bench_e');
      await c.query(`CREATE UNLOGGED TABLE bench_e (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, transfer_id bigint, account_id bigint, direction char(1), amount bigint, created_at timestamptz)`);
      for (const d of ddl) await c.query(d);
      const t0 = performance.now();
      await c.query(`INSERT INTO bench_e (transfer_id, account_id, direction, amount, created_at)
                     SELECT g, (g::bigint * 7919) % 4000, 'D', 100, now() - (g * interval '1 second') FROM generate_series(1, 300000) g`);
      results.push([label, performance.now() - t0]);
    }
    await c.query('DROP TABLE IF EXISTS bench_e');
    const baseMs = results[0][1];
    w('| Indexes besides the primary key | Insert time | vs. none |');
    w('|---|---|---|');
    for (const [label, ms] of results) w(`| ${label} | ${ms.toFixed(0)} ms | ${(ms / baseMs).toFixed(2)}x |`);
  } finally {
    c.release();
  }
  w();
  await writeFile(new URL('../docs/explain.md', import.meta.url), md);
  await pool.end();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
